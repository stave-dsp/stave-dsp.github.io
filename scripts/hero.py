#!/usr/bin/env python3
"""The hero's code is the `stave` crate's own example at a release tag.

That example is a doctest in stave-dsp/stave (crates/stave/src/lib.rs),
compiled and run by the framework's CI, so the code on this page builds
against the release it names. This script copies it into index.html,
between the `hero:begin` and `hero:end` markers, highlighted with the
page's classes. The site itself stays plain HTML: no build step, just
run this when the framework releases.

    python3 scripts/hero.py              # the newest release tag
    python3 scripts/hero.py v0.3.0       # a given tag
    python3 scripts/hero.py --check      # fail if index.html is not the newest
"""

import html
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

REPO = "stave-dsp/stave"
SOURCE = "crates/stave/src/lib.rs"
PAGE = Path(__file__).resolve().parent.parent / "index.html"
BLOCK = re.compile(r"<!-- hero:begin [^>]*-->.*?<!-- hero:end -->", re.S)

KEYWORDS = {
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
    "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
    "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super",
    "trait", "true", "type", "unsafe", "use", "where", "while",
}
TOKEN = re.compile(
    r"(?P<c>//[^\n]*)"
    r"|(?P<s>\"(?:\\.|[^\"\\])*\")"
    r"|(?P<a>#\[[^\]]*\])"
    r"|(?P<n>\b\d[\d_]*(?:\.\d+)?\b)"
    r"|(?P<w>\b[A-Za-z_][A-Za-z0-9_]*\b)"
)


def newest_tag() -> str:
    out = subprocess.run(
        ["git", "ls-remote", "--tags", "--refs", f"https://github.com/{REPO}"],
        check=True, capture_output=True, text=True,
    ).stdout
    tags = re.findall(r"refs/tags/(v(\d+)\.(\d+)\.(\d+))$", out, re.M)
    if not tags:
        sys.exit(f"no release tags on {REPO}")
    return max(tags, key=lambda t: tuple(int(x) for x in t[1:]))[0]


def example(tag: str) -> str:
    url = f"https://raw.githubusercontent.com/{REPO}/{tag}/{SOURCE}"
    with urllib.request.urlopen(url) as r:
        src = r.read().decode()
    docs = [l[4:] if l.startswith("//! ") else l[3:] for l in src.splitlines() if l.startswith("//!")]
    try:
        start = docs.index("```") + 1
        end = docs.index("```", start)
    except ValueError:
        sys.exit(f"{SOURCE} at {tag} has no example in its crate docs")
    # Doctest-hidden lines (`# ...`) are not part of what a reader sees.
    lines = [l for l in docs[start:end] if not (l == "#" or l.startswith("# "))]
    return "\n".join(lines)


def highlight(code: str) -> str:
    out, at = [], 0
    for m in TOKEN.finditer(code):
        out.append(html.escape(code[at:m.start()], quote=False))
        text = html.escape(m.group(), quote=False)
        kind = m.lastgroup
        if kind == "w":
            out.append(f'<span class="k">{text}</span>' if m.group() in KEYWORDS else text)
        else:
            cls = {"c": "c", "s": "s", "a": "k", "n": "n"}[kind]
            out.append(f'<span class="{cls}">{text}</span>')
        at = m.end()
    out.append(html.escape(code[at:], quote=False))
    return "".join(out)


def render(tag: str) -> str:
    link = f"https://github.com/{REPO}/blob/{tag}/{SOURCE}"
    return (
        f"<!-- hero:begin {tag} (generated by scripts/hero.py; do not edit) -->\n"
        f'          <div class="window-bar"><span></span><span></span><span></span>'
        f'<em>a whole plugin · <a href="{link}">the stave crate\'s example</a>, {tag}, doctested</em></div>\n'
        f"<pre><code>{highlight(example(tag))}</code></pre>\n"
        f"          <!-- hero:end -->"
    )


def main() -> None:
    args = sys.argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    tag = args[0] if args else newest_tag()
    page = PAGE.read_text()
    if not BLOCK.search(page):
        sys.exit("index.html has no hero:begin/hero:end block")
    updated = BLOCK.sub(lambda _: render(tag), page, count=1)
    if check:
        if updated != page:
            sys.exit(f"index.html's hero is not the stave crate's example at {tag}: run python3 scripts/hero.py")
        print(f"hero: the stave crate's example at {tag}")
        return
    PAGE.write_text(updated)
    print(f"hero: wrote the stave crate's example at {tag}")


if __name__ == "__main__":
    main()
